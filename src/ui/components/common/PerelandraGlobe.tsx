export function PerelandraGlobe({ width, height }: PerelandraGlobeProps): React.ReactNode {
  const [frame, setFrame] = useState(0);

  useEffect(() => {
    const interval = setInterval(() => {
      setFrame((f) => (f + 1) % ASCII_GLOBE_FRAMES.length);
    }, 400);
    return () => clearInterval(interval);
  }, []);

  const currentFrame = ASCII_GLOBE_FRAMES[frame];
  const globeHeight = currentFrame.length;
  const globeWidth = Math.max(...currentFrame.map((line) => line.length));

  const paddingTop = Math.max(0, Math.floor((height - globeHeight - 2) / 2));
  const paddingLeft = Math.max(0, Math.floor((width - globeWidth) / 2));

  return (
    <box
      style={{
        flexDirection: 'column',
        alignItems: 'center',
        justifyContent: 'center',
        width,
        height,
        paddingTop,
      }}
    >
      <text fg={theme.textMuted} style={{ marginBottom: 1, paddingLeft }}>
        {'✧ Venus / Perelandra ✧'}
      </text>
      {currentFrame.map((line, idx) => (
        <text key={idx} fg={theme.palette.teal} style={{ paddingLeft }}>
          {line
            .replace(/\*/g, '✦')
            .replace(/o/g, '◌')
            .replace(/#/g, '⌂')}
        </text>
      ))}
      <text fg={theme.textMuted} style={{ marginTop: 1, paddingLeft }}>
        {'~ floating islands ~'}
      </text>
    </box>
  );
}
